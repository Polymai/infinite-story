let currentLocale = "en";

export function initLocale() {
  const saved = readLocal(STORAGE_KEY, "en");
  currentLocale = SUPPORTED.includes(saved) ? saved : "en";
  document.documentElement.lang = currentLocale;
  return currentLocale;
}

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  currentLocale = SUPPORTED.includes(locale) ? locale : "en";
  writeLocal(STORAGE_KEY, currentLocale);
  document.documentElement.lang = currentLocale;
  return currentLocale;
}

export function nextLocale() {
  return currentLocale === "sv" ? "en" : "sv";
}

export function t(key, params = {}) {
  const phrase = dictionary[currentLocale]?.[key] || dictionary.en[key] || key;
  return phrase.replace(/\{(\w+)\}/g, (_match, name) => String(params[name] ?? ""));
}

export function storyLanguageLabel(language = "en") {
  const key = SUPPORTED_LANGUAGE_KEYS[language] || "lang.en";
  return t(key);
}

const SUPPORTED_LANGUAGE_KEYS = {
  en: "lang.en",
  sv: "lang.sv",
  es: "lang.es",
  fr: "lang.fr",
  de: "lang.de",
};

export function genreLabel(genre) {
  const key = String(genre || "").toLowerCase().replace(/\s+/g, "-");
  return dictionary[currentLocale]?.[`genre.${key}`] || String(genre || "");
}

export function storyStatusLabel(status) {
  const key = String(status || "").toLowerCase();
  return dictionary[currentLocale]?.[`storyStatus.${key}`] || String(status || "");
}

export function audienceLabel(audience) {
  const key = String(audience || "adult").toLowerCase();
  return dictionary[currentLocale]?.[`audience.${key === "middle-grade" ? "middleGrade" : key === "young-adult" ? "youngAdult" : key === "all-ages" ? "allAges" : "adult"}`] || String(audience || "");
}

export function translatedPlan(plan = {}) {
  return {
    name: dictionary[currentLocale]?.[`plan.${plan.plan_key}.name`] || plan.name,
    description: dictionary[currentLocale]?.[`plan.${plan.plan_key}.description`] || plan.description,
  };
}

export function translatedAchievement(achievement = {}) {
  const key = achievement.achievement_key || achievement.key;
  return {
    name: dictionary[currentLocale]?.[`ach.${key}.name`] || achievement.name,
    description: dictionary[currentLocale]?.[`ach.${key}.description`] || achievement.description,
  };
}
